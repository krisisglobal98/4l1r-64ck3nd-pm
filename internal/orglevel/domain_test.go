package orglevel

import (
	"encoding/json"
	"strings"
	"testing"

	"alir.local/pm-service/internal/platform/record"
)

type V = record.Values

func problemsOf(v V) map[string]string {
	_, ps := Parse(v)
	out := map[string]string{}
	for _, p := range ps {
		out[p.Field] = p.Message
	}
	return out
}

func TestParseValid(t *testing.T) {
	in, ps := Parse(V{"name": "Divisi", "rank": json.Number("6"), "description": ""})
	if len(ps) != 0 {
		t.Fatalf("unexpected problems %v", ps)
	}
	if in.Name != "Divisi" || in.Rank != 6 || in.Description != nil || !in.Active {
		t.Fatalf("got %+v", in)
	}
	if in, _ := Parse(V{"name": "  Divisi  ", "rank": 6}); in.Name != "Divisi" {
		t.Fatalf("name is trimmed: %q", in.Name)
	}
	in, _ = Parse(V{"name": "X", "rank": "2", "active": false, "validFrom": "2026-01-01", "validTo": "2026-12-31"})
	if in.Rank != 2 || in.Active || *in.ValidFrom != "2026-01-01" || *in.ValidTo != "2026-12-31" {
		t.Fatalf("rank as text, inactive, validity: %+v", in)
	}
}

func TestParseNeverReadsTheCode(t *testing.T) {
	in, ps := Parse(V{"code": "a b", "name": "A", "rank": 1})
	if len(ps) != 0 || in.Code != "" {
		t.Fatalf("the code is generated by the service, not taken from the form: %+v %v", in, ps)
	}
}

func TestParseProblemsMatchTheForm(t *testing.T) {
	ok := func(extra V) V {
		v := V{"name": "A", "rank": 1}
		for k, x := range extra {
			v[k] = x
		}
		return v
	}
	cases := []struct {
		name  string
		v     V
		field string
		msg   string
	}{
		{"name required", ok(V{"name": "  "}), "name", "Nama wajib diisi."},
		{"name with NUL", ok(V{"name": "a\x00b"}), "name", "Nama berisi karakter yang tidak diizinkan."},
		{"description with NUL", ok(V{"description": "a\x00"}), "description", "Deskripsi berisi karakter yang tidak diizinkan."},
		{"rank beyond the column", ok(V{"rank": json.Number("3000000000")}), "rank", "Urutan paling besar 2147483647."},
		{"name too long", ok(V{"name": strings.Repeat("n", 151)}), "name", "Nama paling banyak 150 karakter."},
		{"description too long", ok(V{"description": strings.Repeat("d", 501)}), "description", "Deskripsi paling banyak 500 karakter."},
		{"active not a boolean", ok(V{"active": "ya"}), "active", "Status aktif harus ya atau tidak."},
		{"bad date", ok(V{"validFrom": "2026-13-01"}), "validFrom", "Berlaku mulai bukan tanggal yang sah (format YYYY-MM-DD)."},
		{"end before start", ok(V{"validFrom": "2026-06-01", "validTo": "2026-05-31"}), "validTo", "Tanggal selesai tidak boleh sebelum tanggal mulai."},
		{"rank required", ok(V{"rank": nil}), "rank", "Urutan wajib diisi."},
		{"rank below 1", ok(V{"rank": json.Number("0")}), "rank", "Urutan minimal 1."},
		{"rank not a number", ok(V{"rank": "abc"}), "rank", "Urutan minimal 1."},
		{"rank not whole", ok(V{"rank": json.Number("1.5")}), "rank", "Urutan harus bilangan bulat."},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := problemsOf(c.v)[c.field]; got != c.msg {
				t.Fatalf("%s: got %q, want %q", c.field, got, c.msg)
			}
		})
	}
}

func TestBuiltInLevels(t *testing.T) {
	for _, c := range []string{"group", "region", "wilayah", "company", "unit", "UNIT"} {
		if !IsBuiltIn(c) {
			t.Errorf("%s should be built in", c)
		}
	}
	if IsBuiltIn("divisi") {
		t.Error("divisi is not built in")
	}
}
